"""Состояния (FSM — машина состояний).

Состояние — это «режим», в котором сейчас находится пользователь.
Когда он нажал «Техподдержка», мы переводим его в режим
waiting_message, и следующее его сообщение считаем вопросом.
"""
from aiogram.fsm.state import State, StatesGroup


class SupportForm(StatesGroup):
    """Режимы для общения с техподдержкой."""

    waiting_message = State()  # ждём, пока человек напишет вопрос
